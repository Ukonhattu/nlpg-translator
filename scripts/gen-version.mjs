// Writes src/version.ts from package.json so the library can report its own
// version without reading files at runtime. Runs as part of `npm run build`.
import { URL } from "node:url";
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const out = new URL("../src/version.ts", import.meta.url);
const content =
  `// Generated by scripts/gen-version.mjs from package.json. Do not edit.\n` +
  `export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n`;

let current = "";
try {
  current = readFileSync(out, "utf8");
} catch {
  /* first run */
}
if (current !== content) writeFileSync(out, content);
